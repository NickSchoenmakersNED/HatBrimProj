volatile uint32_t fb_period = 0;
volatile uint32_t fb_high = 0;
volatile uint32_t ctrl_pulse = 0;

enum LDRIndex {
	LDR_RIGHT,  // 0
	LDR_LEFT,   // 1
};

volatile uint32_t LDRValues[2];

const int32_t DIFF_ON  = 300;
const int32_t DIFF_OFF = 150;

// From documentation:
// ---------------------------------------------
/*
 * Source: servo control signal vs. rotation (see question 1 for datasheet page)
 *
 * +-------------------+---------------------------+-----------------+-----------------------------------+
 * |                   | Clockwise                 | Stop            | Counterclockwise                  |
 * |                   | (faster to slower)        |                 | (slower to faster)                |
 * +-------------------+---------------------------+-----------------+-----------------------------------+
 * | tControl, +/-10us | 1280 .... 1480            | 1480 ... 1520   | 1520 .... 1720                    |
 * | RPM, +/-15        | 140 ... 0                 | 0               | 0 ... -140                        |
 * +-------------------+---------------------------+-----------------+-----------------------------------+
 */
// ---------------------------------------------
// generated by claude: https://claude.ai/share/cb2133f3-9c72-4555-be2d-b00f414dd507
const uint32_t MOTOR_STOP_PULSE  = 1480;
const uint32_t MOTOR_PULSE_RANGE = 220;

static int arrNumbersLeft[10] = { 0 };
static int arrNumbersRight[10] = { 0 };

// here every object is created. they are globals so that they can be seen with live expression

// light sensors
AdcScanner adcScanner(&hadc1, LDRValues, sizeof(LDRValues) / sizeof(LDRValues[0]));
LightSensor leftSensor(adcScanner, LDR_LEFT, arrNumbersLeft, sizeof(arrNumbersLeft) / sizeof(int));
LightSensor rightSensor(adcScanner, LDR_RIGHT, arrNumbersRight, sizeof(arrNumbersRight) / sizeof(int));
LightSensing lightSensing(adcScanner, leftSensor, rightSensor);
FollowLightStrategy followStrategy(lightSensing, DIFF_ON, DIFF_OFF);
// motor
Motor motor(&htim1, TIM_CHANNEL_1, MOTOR_STOP_PULSE, MOTOR_PULSE_RANGE);
// hat controller
HatController hat(lightSensing, followStrategy, motor);

void app_init(void)
{
	motor.init();
	HAL_TIM_IC_Start(&htim2, TIM_CHANNEL_1);
	HAL_TIM_IC_Start_IT(&htim2, TIM_CHANNEL_2);

	adcScanner.init();

	/* first measurement needs up to 180 ms (datasheet max) before it is valid. */
	HAL_Delay(180);

	// the initialization is complete
	hat.handleEvent(HatController::Event::INIT_COMPLETE);
}

void app_loop(void)
{
	hat.update();

	HAL_Delay(100);
}

